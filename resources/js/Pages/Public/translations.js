export function translate(text, locale) {
  if (locale !== 'id' || typeof text !== 'string') {
    return text;
  }

  return id[text] ?? text;
}

export function translatePackage(pkg, locale) {
  if (locale !== 'id') {
    return pkg;
  }

  const knownPackage = packages[pkg.slug] ?? {};

  return {
    ...pkg,
    ...knownPackage,
    short_description: translate(pkg.short_description, locale),
    full_description: knownPackage.full_description ?? translate(pkg.full_description, locale),
    included_services: pkg.included_services?.map((service) => translate(service, locale)),
    price_unit: pkg.price_unit === 'per_person' ? 'per orang' : 'per grup',
  };
}

export function translateFaq(faq, locale) {
  if (locale !== 'id') {
    return faq;
  }

  return {
    ...faq,
    question: translate(faq.question, locale),
    answer: translate(faq.answer, locale),
  };
}
